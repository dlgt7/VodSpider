            json.put(key2, action);
            // 请求体字段：图片URL
            String key3 = "vod_pic";
            if (pic != null) {
                json.put(key3, pic);
            } else {
                json.put(key3, FishCrypto.pic());
            }
            // 请求体字段：数据
            String key4 = "vod_remarks";
            json.put(key4, data);
            // 请求体字段：扩展信息
